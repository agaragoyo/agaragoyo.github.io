// 내 방의 펫(F30, src/pet.js)의 그림과 색. 종류 여덟 가지에 색이 네 가지씩 있고, 펫 바꾸기 창(src/pet-picker.js)에서 고른다.
// 병아리는 쓰다듬은 횟수가 열 번이 되면 닭으로 자란다. 닭은 목록에 따로 있지만 펫 바꾸기 창의 종류 줄에는 나오지 않고 병아리 단추가 대신한다.
//
// 그림 규격
//   24칸 × 20칸이고 한 글자가 한 칸, '.'은 빈칸이다(src/icons.js의 PIXEL과 같은 방식). 모두 왼쪽을 본 그림이고, 오른쪽으로 갈 때는 좌우를 뒤집는다.
//   한 칸은 무대 2px 안팎이라(--pet-cell) 그림은 48×40px쯤이고, 아바타(64×104px) 폭의 75%다.
//   글자는 o 겉선, b 바탕, d 그림자, w 배, m 무늬, e 눈, h 눈 하이라이트(흰색), c 볼, s 바닥 그림자다.
//   아기처럼 보이게 머리를 그림 키의 60% 넘게, 몸보다 넓게 그렸다. 눈은 2×3칸에 하이라이트 한 칸을 넣어 머리 아래쪽 절반에 5칸 떨어뜨려 두었다.
//   머리 가운데는 모든 종류가 9번 칸이라(src/pet.js의 HEAD_X) 눈은 5~6번과 12~13번 칸, 코와 부리는 9번 칸을 가운데로 그린다.
//   강아지, 고양이, 코끼리, 코알라는 같은 머리와 네 발 몸에 귀, 꼬리, 코만 달리 붙였다. 머리나 몸을 고치면 네 종류를 함께 고친다.
//
// 칸
//   sit은 앉은 그림, walk1과 walk2는 걷는 그림 두 장이다(반 칸마다 바꾼다). walk1이 없으면 앉은 그림을 쓴다.
//   fly1과 fly2는 나는 그림 두 장(날개를 든 장과 내린 장)이다. 말풍선 암호로 날아오는 비둘기(src/pigeon.js)가 쓰고, 지금은 비둘기에만 있다.
//   loaf는 가구 위에서 앞발을 접고 웅크린 그림(식빵 자세)이다. 가구에 올라가는 종류(mood.perch, 고양이)에만 두고, 앉은 그림보다 낮고 길다.
//   머리는 앉은 그림의 머리를 한 줄 내려 그대로 쓰고(머리 가운데 9번 칸과 눈 자리가 같다), 몸은 머리 뒤로 눕히고 꼬리는 몸 아래로 감는다.
//   숨 쉬는 그림과 눈 감은 그림은 src/pet.js가 앉은 그림과 웅크린 그림에서 만든다. breath는 숨을 들이쉴 때 빼는 줄의 번호(0부터)이고, 그 위가 한 칸 내려온다.
//   웅크린 그림도 같은 줄을 빼므로, 그 줄은 두 그림 모두 머리가 없는 줄(앞발이나 다리)이어야 한다.
//   눈 감은 그림은 하이라이트(h)가 든 눈을 위 칸의 색으로 덮고 맨 아래 줄만 남겨 만든다. 그래서 눈에는 h를 꼭 넣는다.
//   colors는 색 네 가지다. b 바탕, d 그림자, w 배, m 무늬, e 눈, c 볼이고, 겉선(o)은 적지 않는다. 겉선은 바탕의 명도를 35 낮추고
//   채도를 30% 줄인 색으로 칠한다(바탕화면 아이콘과 같은 방법, src/pet.js의 outline). 첫 색이 펫 바꾸기 창의 종류 단추에 그려진다.
//   색은 2026-11-14에 정한 파스텔 픽셀 방향과 가구 그림의 색에서 골랐고, 갈색과 골든은 나무 바닥보다 밝게 두었다.
//   name과 색 이름은 펫 바꾸기 창의 단추 폭에 맞춰 네 글자까지 쓴다(src/pet-picker.js의 LABEL_W).
//   grow는 자라서 될 종류의 id다. 쓰다듬은 횟수가 src/pet.js의 GROW_PATS번이 되면 같은 색 id의 그 종류로 바뀌므로, 자란 종류에도
//   같은 색 id를 둔다(이름과 색은 달라도 된다. 노랑 병아리는 흰 닭이 된다). 자란 종류의 grown은 그때 아바타가 하는 말이다.
