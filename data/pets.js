// 칸
//   sit은 앉은 그림, walk1과 walk2는 걷는 그림 두 장이다(반 칸마다 바꾼다). walk1이 없으면 앉은 그림을 쓴다.
//   숨 쉬는 그림과 눈 감은 그림은 src/pet.js가 앉은 그림에서 만든다. breath는 숨을 들이쉴 때 빼는 줄의 번호(0부터)이고, 그 위가 한 칸 내려온다.
