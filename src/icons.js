// 아이콘 자리 크기(px)마다 쓰는 그림의 칸 수. 게임기 화면의 40px와 32px 자리에는 16칸 그림을 쓴다.
// 24칸 그림을 40px에 놓으면 한 칸이 1.67배라 정수 픽셀로 맞출 때 크기가 0.7배와 1.3배 사이를 크게 오가고, 16칸 그림은 2배 남짓으로 고르게 맞는다
// 바탕화면의 기본 앱은 48px 자리에 48칸 그림(한 칸이 무대 1px)을 쓴다. 그 그림의 크기는 SLOTS가 아니라 fitPixelIcons의 --pixel-48dot이 정한다
const SLOTS = { 48: 24, 40: 16, 32: 16, 24: 24, 16: 16 };

// 그림 한 칸이 화면 픽셀 정수 개가 되도록 자리마다 그림 크기를 고른다. main.js의 fit()이 무대 배율이 바뀔 때마다 부른다(known-issues 67).
// 무대는 창 크기에 맞춰 정수가 아닌 배율로 늘고 준다. 그대로 그리면 0.91배에서 한 칸이 1.82픽셀이 되어 어떤 칸은 1픽셀, 어떤 칸은 2픽셀이 되고,
// 한 칸이 1픽셀보다 작아지면 칸이 통째로 빠진다. 그래서 원래 크기의 0.7~1.4배 안에서 한 칸이 정수 픽셀이 되는 가장 가까운 크기로 그린다.
// 그런 크기가 없으면 원래 크기로 두고, 한 칸이 1픽셀보다 작을 때만 부드럽게 줄인다(칸이 빠지는 것보다 낫다).
// style: CSS 변수를 넣을 곳(document.documentElement.style), scale: 무대 배율, dpr: 화면 픽셀 비율(devicePixelRatio)
export function fitPixelIcons(style, scale, dpr) {
  // 원래 크기로 그리면 한 칸이 raw 화면 픽셀인 그림을, 한 칸이 정수 픽셀이 되게 할 때의 픽셀 수(원래 크기의 0.7~1.4배 안에서 가장 가까운 것). 없으면 undefined
  const nearest = raw => [Math.floor(raw), Math.ceil(raw)]
    .filter(n => n >= 1 && n / raw >= 0.7 && n / raw <= 1.4)
    .sort((a, b) => Math.abs(Math.log(a / raw)) - Math.abs(Math.log(b / raw)))[0];
  for (const [slot, grid] of Object.entries(SLOTS)) {
    const raw = slot / grid * scale * dpr; // 그림 한 칸이 차지하는 화면 픽셀
    const k = nearest(raw);
    style.setProperty(`--pixel-${slot}`, (k ? grid * k / (scale * dpr) : slot) + 'px');
    style.setProperty(`--pixel-${slot}-render`, k || raw >= 1 ? 'crispEdges' : 'auto');
  }
  // 48칸 그림이 있는 아이콘(바탕화면의 기본 앱)은 화면 크기와 상관없이 48칸 그림을, 한 점이 화면 픽셀 정수 개가 되는 크기로 또렷하게 그린다.
  // 정수는 원래 크기(무대 48px)에 가장 가까운 것으로 고르되 1보다 작게는 고르지 않는다. 그림이 48px보다 크면 style.css가 아이콘 자리와 바탕화면 칸을 그만큼 늘인다.
  // 다만 화면에서 윈도우 바탕화면의 작은 아이콘(CSS 32px)보다 작아지는 정수는 고르지 않는다. 2880×1800 랩탑의 200%는 무대가 0.69~0.72배라
  // 가장 가까운 정수가 크롬의 즐겨찾기 줄 하나로 1과 2 사이를 오가는데, 1이면 아이콘이 화면에서 24px로 작았다(2026-11-23). 이 하한으로 200%와 175%는 늘 한 점 2픽셀이다.
  // 1366×768(무대 0.56~0.59배)은 한 점 1픽셀로 자리의 1.7~1.8배, 2880×1800 랩탑의 150~200%는 한 점 2픽셀로 1.3~1.5배가 된다.
  // 처음(2026-11-23)에는 자리를 48px로 두고 그림을 맞추느라 이런 화면에서 24칸 그림을 썼는데, 그러면 랩탑에서 48칸 그림을 볼 수 없었다
  const raw48 = scale * dpr;
  const near = [Math.floor(raw48), Math.ceil(raw48)].filter(n => n >= 1)
    .sort((a, b) => Math.abs(Math.log(a / raw48)) - Math.abs(Math.log(b / raw48)))[0];
  const k48 = Math.max(near, Math.ceil(32 * dpr / 48 - 1e-9));
  style.setProperty('--pixel-48dot', 48 * k48 / (scale * dpr) + 'px');
  // 내 방의 펫(src/pet.js)과 하트도 한 칸이 2px인 픽셀 그림이다. 바닥에 서서 아바타와 크기를 견주므로 반짝임과 달리
  // 원래 크기에 가장 가까운 정수를 고르고, 아이콘처럼 그런 정수가 없으면 원래 크기로 둔다. 펫은 이 값으로 가구와의 앞뒤를 따질 그림 크기도 잰다
  const pet = nearest(2 * scale * dpr);
  style.setProperty('--pet-cell', (pet ? pet / (scale * dpr) : 2) + 'px');
  style.setProperty('--pet-render', pet || 2 * scale * dpr >= 1 ? 'crispEdges' : 'auto');
  // 담긴 가구 반짝임(style.css의 .has-like::after)도 한 칸이 2px인 픽셀 그림이라 한 칸을 정수 화면 픽셀로 맞춘다.
  // 눈에 띄는 것이 목적이라 가까운 정수가 아니라 조금 큰 쪽(0.25를 덜어 올림)을 고르고, 한 칸이 1픽셀보다 작아지는 배율에서도 1픽셀로 둔다.
  style.setProperty('--sparkle-cell', Math.max(1, Math.ceil(2 * scale * dpr - 0.25)) / (scale * dpr) + 'px');
}

